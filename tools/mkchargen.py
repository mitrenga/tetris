#!/usr/bin/env python3
"""Writes the character generator of the 15IE-00-013 terminal as an app module.

Usage: mkchargen.py [--rom sources/rom/ie15.zip] [-o app/ie15Chargen.js]

Reads ``chargen-15ie.bin`` (256 glyphs, 8 bytes each, bits 7-1 of a byte are
the 7 pixels of a row, MAME ``ie15``) out of the ROM set and writes it as hex
into ``app/ie15Chargen.js``, which ``app/ie15Terminal.js`` turns into a
TerminalFont. The ROM is checked against the CRC32 and SHA-1 of MAME 0.264
first, so a different dump is never written silently.

The font lives in the project, not in svision (R-061): svision is public,
this project is internal, and the provenance of the dump is not known yet
(sources/rom/README.md).
"""
import argparse, hashlib, os, zipfile, zlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NAME = 'chargen-15ie.bin'
# MAME 0.264, src/devices/machine/ie15.cpp
CRC32 = 0xed16bf6b
SHA1 = '6af9fb75f5375943d5c0ce9ed408e0fb4621b17e'


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--rom', default=os.path.join(ROOT, 'sources', 'rom', 'ie15.zip'))
    ap.add_argument('-o', default=os.path.join(ROOT, 'app', 'ie15Chargen.js'))
    args = ap.parse_args()

    data = zipfile.ZipFile(args.rom).read(NAME)
    crc = zlib.crc32(data) & 0xFFFFFFFF
    sha1 = hashlib.sha1(data).hexdigest()
    if len(data) != 2048 or crc != CRC32 or sha1 != SHA1:
        raise SystemExit('%s: %d bytes, CRC32 %08x, SHA-1 %s - not the dump MAME 0.264 knows'
                         % (NAME, len(data), crc, sha1))

    rows = [data[i:i+64].hex().upper() for i in range(0, len(data), 64)]
    with open(args.o, 'w') as f:
        f.write("// begin code\n\n")
        f.write("/**\n")
        f.write(" * The character generator ROM of the 15IE-00-013 terminal (%s, 2048\n" % NAME)
        f.write(" * bytes, CRC32 %08x, SHA-1 %s):\n" % (crc, sha1))
        f.write(" * 256 glyphs of 8 bytes, bits 7-1 of a byte the 7 pixels of a row. Codes\n")
        f.write(" * 000-177 Latin, 200-377 Cyrillic; 177 and 377 are the solid block.\n")
        f.write(" *\n")
        f.write(" * Generated by tools/mkchargen.py from sources/rom/ie15.zip - do not edit.\n")
        f.write(" * Foreign content, kept in the project as the terminal's font (R-061).\n")
        f.write(" */\n")
        f.write("export const IE15Chargen = [\n")
        f.write(',\n'.join("  '%s'" % r for r in rows))
        f.write("\n].join('');\n")
    print('%s: %d glyphs' % (os.path.relpath(args.o, ROOT), len(data) // 8))


if __name__ == '__main__':
    main()
