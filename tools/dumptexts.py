#!/usr/bin/env python3
"""Writes the texts and data of the program image as a worker script.

Usage: dumptexts.py [-o app/programTexts.js]

The converted game (app/tetrisLogic.js) keeps its state at the original's
addresses, and the texts it writes to the terminal are read from those
addresses too - the strings of TET.SAV in KOI-7, the cell of a piece, the
borders of the title. This tool takes every text and data range the
disassembly knows (sources/asm/hints.json) from both revisions on the games
disk and writes them as ``[address, hex]`` pairs:

- ``TET.SAV``: the authority, pieces drawn with two DEL characters (177);
- ``TETRIS.SAV``: the later revision, pieces drawn with ``[]``.

The two differ in 10 bytes on five places (sources/disk/README.md); one of
them, ``005306``, is the immediate operand of the instruction that fills the
draw string with the cell, so the range ``005306``-``005307`` is taken as
data as well.
"""
import argparse, hashlib, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GAMES = os.path.join(ROOT, 'sources', 'disk', 'games')
HINTS = os.path.join(ROOT, 'sources', 'asm', 'hints.json')
REVISIONS = (('TET', 'TET.SAV'), ('TETRIS', 'TETRIS.SAV'))
# the cell of the draw string is an immediate operand (MOV #77577,1200(R0))
EXTRA = [(0o5306, 0o5310, 'cell of the draw string (immediate operand)')]


def ranges():
    with open(HINTS) as f:
        hints = json.load(f)
    out = [(int(lo, 8), int(hi, 8), name) for lo, hi, name in hints['text'] + hints['data']]
    return sorted(out + EXTRA)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('-o', default=os.path.join(ROOT, 'app', 'programTexts.js'))
    args = ap.parse_args()

    spans = ranges()
    revisions = {}
    for key, name in REVISIONS:
        with open(os.path.join(GAMES, name), 'rb') as f:
            image = f.read()
        revisions[key] = {
            'file': name,
            'sha256': hashlib.sha256(image).hexdigest(),
            'texts': [[lo, image[lo:hi].hex()] for lo, hi, _ in spans],
        }

    with open(args.o, 'w') as f:
        f.write("// classic script (importScripts): no import, no export - R-001, R-048.\n")
        f.write("// begin code\n\n")
        f.write("/**\n")
        f.write(" * Texts and data of the program image, by revision: `[address, hex]` pairs\n")
        f.write(" * the converted game loads at the original's addresses (app/tetrisLogic.js).\n")
        f.write(" * TET = TET.SAV (the authority, cells of two DEL characters), TETRIS =\n")
        f.write(" * TETRIS.SAV (the later revision, cells `[]`). Addresses decimal.\n")
        f.write(" *\n")
        f.write(" * Generated by tools/dumptexts.py from sources/disk/games/ - do not edit.\n")
        f.write(" */\n")
        f.write("var ProgramTexts = ")
        f.write(json.dumps(revisions, separators=(',', ':')))
        f.write(";\n\n")
        f.write("if (typeof self !== 'undefined') { self.ProgramTexts = ProgramTexts; }\n")
        f.write("if (typeof module !== 'undefined' && module.exports) { module.exports = ProgramTexts; }\n")
    diff = sum(1 for (_, a), (_, b) in zip(revisions['TET']['texts'], revisions['TETRIS']['texts'])
               for x, y in zip(bytes.fromhex(a), bytes.fromhex(b)) if x != y)
    print('%s: %d ranges, %d bytes a revision, %d bytes differ'
          % (os.path.relpath(args.o, ROOT), len(spans), sum(hi - lo for lo, hi, _ in spans), diff))


if __name__ == '__main__':
    main()
