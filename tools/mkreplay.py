#!/usr/bin/env python3
"""Writes recorded runs of the original as an app module for playback.

Usage: mkreplay.py [TRACE.json ...] [-o app/recordedRuns.js]

Takes runs recorded by tracecoverage.py --trace (SIMH, TET.SAV under RT-11;
default: the playback runs in sources/media/play/, the game without keys
first) and writes what the original sent down the line - every chunk of
output with the instruction count it came at - into ``app/recordedRuns.js``.
The playback runs are recorded with a 9600 baud console (``--tto-time``) and
keys at a human pace; the coverage runs of M0 (sources/media/games/) are a
machine gun of keys and garble the playfield with RT-11's echo.

Until the game itself is converted (M2/M3), the worker plays these back as
the host, so the terminal of svision shows the original's own title and
game screens (M1).

Times stay in instructions, relative to the start of each run; how many
instructions a millisecond is belongs to the time model (M3).
"""
import argparse, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('traces', nargs='*')
    ap.add_argument('-o', default=os.path.join(ROOT, 'app', 'recordedRuns.js'))
    args = ap.parse_args()
    traces = args.traces or [os.path.join(ROOT, 'sources', 'media', 'play', name + '.json')
                             for name in ('idle0', 'play0', 'play3', 'play5')]
    if not traces:
        raise SystemExit('no traces (run tools/tracecoverage.py --trace first)')

    runs = []
    for path in traces:
        with open(path) as f:
            trace = json.load(f)
        start = trace['start']
        runs.append({
            'name': os.path.splitext(os.path.basename(path))[0],
            'command': trace['command'],
            'ttoTime': trace.get('ttoTime', 100),
            'length': trace['end'] - start,
            'output': [[t - start, h] for t, h in trace['output']],
            'keys': [[t - start, h] for t, h in trace['keys']],
        })

    with open(args.o, 'w') as f:
        f.write("// begin code\n\n")
        f.write("/**\n")
        f.write(" * Runs of the original recorded in SIMH PDP-11 3.8 (TET.SAV under RT-11):\n")
        f.write(" * what the program sent down the line, chunk by chunk, with the instruction\n")
        f.write(" * count it came at (relative to the start of the run), and the keys typed.\n")
        f.write(" * Each chunk is hex. The worker plays them back as the host until the game\n")
        f.write(" * itself is converted (M1). `ttoTime`: instructions per output character.\n")
        f.write(" *\n")
        f.write(" * Generated by tools/mkreplay.py from sources/media/play/ - do not edit.\n")
        f.write(" */\n")
        f.write("export const RecordedRuns = ")
        f.write(json.dumps(runs, separators=(',', ':')))
        f.write(";\n")
    print('%s: %d runs, %d bytes of output'
          % (os.path.relpath(args.o, ROOT), len(runs),
             sum(len(h) // 2 for r in runs for _, h in r['output'])))


if __name__ == '__main__':
    main()
